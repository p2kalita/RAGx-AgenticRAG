###############################################################

from typing import List, Dict, Any, Optional
import pandas as pd


def generate_inferential_summary_table(
    summary_results: List[Dict[str, Any]]
) -> pd.DataFrame:
    """
    Format and sort the inferential analysis results by Cramer's V descending.

    Parameters
    ----------
    summary_results : List[Dict[str, Any]]
        List of result dictionaries generated by the predictor analyses.

    Returns
    -------
    pd.DataFrame
        Formatted summary DataFrame.
    """
    summary_df = pd.DataFrame(summary_results)

    summary_df = summary_df.sort_values(
        by="Cramer's V",
        ascending=False
    )

    print("=" * 90)
    print("SUMMARY OF EXPLORATORY INFERENTIAL ANALYSIS")
    print("=" * 90)

    try:
        display(summary_df)
    except NameError:
        print(summary_df)

    return summary_df


